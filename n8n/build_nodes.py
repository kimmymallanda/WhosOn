"""Builds the n8n Code-node files from the shared JavaScript logic and the project's JSON data.

Run:  python n8n/build_nodes.py

Writes n8n/nodes/*.js (paste each into an n8n Code node, or let Claude update the workflow)
and n8n/checker_cases.json (test cases plus what the Python code answers for them, so
tests/test_n8n_nodes.py can prove the JavaScript matches the Python).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "src"))

import line_times as lt  # noqa: E402
import planner as pl  # noqa: E402
import rules_checker as rc  # noqa: E402

BANNER = "// GENERATED by n8n/build_nodes.py from n8n/src/*.js and data/*.json. Edit those, then rebuild.\n"


def js(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=2)


def js_list(items) -> str:
    """One item per line, so generated data stays short and readable in n8n."""
    return "[\n  " + ",\n  ".join(json.dumps(i, ensure_ascii=False) for i in items) + "\n]"


# --------------------------------------------------------------------------- data

def load():
    roster, cfg, hist = rc.load_json("roster.json"), rc.load_json("league_config.json"), rc.load_json("season_history.json")
    return roster, cfg, hist


# --------------------------------------------------------------------- test cases

def lineup_cases(roster, cfg):
    everyone = {p["id"] for p in roster["players"]}
    avail = sorted(everyone - {"p07", "p09", "p10", "p14"})  # demo week: Gina, Isla, Jess, Nora are out
    base = [["p01", "p02"], ["p03", "p12"], ["p05", "p06"], ["p13", "p15"], ["p08", "p16"]]
    without = lambda ids, x: [i for i in ids if i != x]  # noqa: E731
    return [
        {"case": "Approved lineup", "lineup": base, "available": avail},
        {"case": "Carla drops (R4)", "lineup": base, "available": without(avail, "p03")},
        {"case": "Kara at line 2 (R6)", "lineup": [base[0], ["p11", "p12"]] + base[2:], "available": avail},
        {"case": "Dana at line 2 (legal)", "lineup": [base[0], ["p04", "p12"]] + base[2:], "available": avail},
        {"case": "Pair moves two lines (R5)", "lineup": [["p03", "p12"], ["p05", "p06"], ["p01", "p02"], base[3], base[4]], "available": avail},
        {"case": "Sandbagging (R7)", "lineup": [["p03", "p12"], ["p01", "p02"], ["p05", "p06"], ["p08", "p16"], ["p13", "p15"]], "available": avail},
        {"case": "Winning pair down alone (legal)", "lineup": [["p03", "p12"], ["p01", "p02"], ["p05", "p06"], ["p13", "p15"], ["p08", "p16"]], "available": avail},
        {"case": "Only four lines (R1)", "lineup": base[:4], "available": avail},
        {"case": "One-player line (R1)", "lineup": [["p01"]] + base[1:], "available": avail},
        {"case": "Unknown player (R2)", "lineup": [["p01", "p99"]] + base[1:], "available": avail},
        {"case": "Player in two lines (R3)", "lineup": [["p01", "p02"], ["p01", "p12"]] + base[2:], "available": avail},
        {"case": "Two problems at once", "lineup": [base[0], ["p11", "p12"], ["p05", "p06"], base[3], base[4]], "available": without(avail, "p13")},
    ]


def time_cases():
    return [
        {"match_time": first, "time_window": w}
        for first in ("13:00", "09:30", "10:00")
        for w in (None, "until 16:00", "until 15:30", "until 12:00", "until 18:00", "after 14:00", "after 13:00", "after 16:00", "maybe later")
    ]


PLANNER_KEYS = ("windows", "baseline", "ranking", "exclude", "reserve", "fixed", "k", "node_budget")
LENA = {"p12": "until 16:00"}  # Lena has to leave by 4:00 PM


def planner_cases(roster):
    """Planner scenarios. The first four are the demo scenarios shown in the n8n workflow."""
    everyone = {p["id"] for p in roster["players"]}
    avail = sorted(everyone - {"p07", "p09", "p10", "p14"})
    base = [["p01", "p02"], ["p03", "p12"], ["p05", "p06"], ["p13", "p15"], ["p08", "p16"]]
    drop = lambda ids, *gone: [i for i in ids if i not in gone]  # noqa: E731
    first = "13:00"
    return [
        {"scenario": "Week 3 (Lena leaves by 4:00)", "available": avail, "first_start": first, "windows": LENA},
        {"scenario": "Carla drops at 9pm", "available": drop(avail, "p03"), "first_start": first, "windows": LENA, "baseline": base},
        {"scenario": "Carla and Dana both out", "available": drop(avail, "p03", "p04"), "first_start": first, "windows": LENA, "baseline": base},
        {"scenario": "Only nine players", "available": avail[:9], "first_start": first},
        {"scenario": "Captain ranking", "available": avail, "first_start": first, "ranking": ["p08", "p16", "p01", "p02", "p05", "p06", "p03", "p12", "p13", "p15"]},
        {"scenario": "Fixed pair and a player rested", "available": avail, "first_start": first, "exclude": ["p01"], "fixed": {"3": ["p05", "p06"]}},
        {"scenario": "Emergency sub needed", "available": drop(avail, "p04", "p11", "p13"), "first_start": first, "reserve": ["p04"]},
        {"scenario": "Time limit might not fit", "available": avail, "first_start": first, "windows": {"p12": "until 14:30"}, "fixed": {"2": ["p03", "p12"]}},
        {"scenario": "Search limit reached", "available": avail, "first_start": first, "node_budget": 5},
    ]


def run_planner(c, roster, cfg, state):
    kwargs = {key: c[key] for key in PLANNER_KEYS if key in c}
    return {"scenario": c["scenario"], **pl.plan(roster, cfg, state, c["available"], c["first_start"], **kwargs)}


def expected(roster, cfg, hist):
    state = rc.build_state(hist)
    out_lineups = []
    for c in lineup_cases(roster, cfg):
        v = rc.check_lineup(c["lineup"], roster, cfg, set(c["available"]), state)
        out_lineups.append({
            "case": c["case"],
            "ok": not v,
            "violations": [{"rule_id": x.rule_id, "message": x.message} for x in v],
            "allowed_lines": [rc.allowed_lines_for_pair(p, state, cfg) for p in c["lineup"]],
        })
    out_times = []
    for c in time_cases():
        first = lt.to_min(c["match_time"])
        times = [f"{(first + 60 * k) // 60:02d}:{(first + 60 * k) % 60:02d}" for k in range(3)]
        fit, safe, risky, blocked, notes = {}, [], [], [], []
        for line in range(1, cfg["lines"] + 1):
            r = lt.time_fit(c["time_window"], line, times, cfg)
            fit[str(line)] = r["status"]
            {"ok": safe, "risky": risky, "no": blocked}[r["status"]].append(line)
            if r["status"] != "ok":
                notes.append(f"Line {line} ({r['start']}): {r['why']}")
        out_times.append({**c, "line_fit": fit, "safe_lines": safe, "risky_lines": risky, "blocked_lines": blocked, "line_fit_notes": notes})
    out_planner = [run_planner(c, roster, cfg, state) for c in planner_cases(roster)]
    return {"lineups": out_lineups, "times": out_times, "planner": out_planner}


# ---------------------------------------------------------------------- node files

def build() -> dict:
    roster, cfg, hist = load()
    roster_min = {"players": [{"id": p["id"], "name": p["name"]} for p in roster["players"]]}
    cfg_rules = {k: cfg[k] for k in ("lines", "players_per_line", "pair_move_limit", "individual_move_limit")}
    cfg_time = {"lines": cfg["lines"], "line_duration_hours": cfg["line_duration_hours"]}
    hist_min = {"matches": [{k: m[k] for k in ("match_id", "lineup", "results", "provisional") if k in m} for m in hist["matches"]]}

    rules_core = (HERE / "src" / "rules_core.js").read_text(encoding="utf-8")
    time_core = (HERE / "src" / "time_fit_core.js").read_text(encoding="utf-8")

    rules_node = (
        BANNER
        + "// Node: Rules checker. Input items: { case, lineup: [[id, id] x5], available: [ids] }.\n"
        + f"const ROSTER = {{ players: {js_list(roster_min['players'])} }};\n"
        + f"const CONFIG = {json.dumps(cfg_rules)};\n"
        + f"const HISTORY = {{ matches: {js_list(hist_min['matches'])} }};\n\n"
        + rules_core
        + "\nconst state = buildState(HISTORY);\n"
        + "return $input.all().map((item) => {\n"
        + "  const c = item.json;\n"
        + "  const violations = checkLineup(c.lineup, ROSTER, CONFIG, new Set(c.available), state);\n"
        + "  return { json: {\n"
        + "    case: c.case,\n    ok: violations.length === 0,\n    violations,\n"
        + "    allowed_lines: c.lineup.map((pair) => allowedLinesForPair(pair, state, CONFIG)),\n"
        + "  } };\n});\n"
    )
    time_node = (
        BANNER
        + "// Node: Line time fit. Adds, to each recorded availability item, which lines fit the player's time limit.\n"
        + "// Input fields used: match_time (\"13:00\", the first line's start) and time_window (\"until 16:00\" or null).\n"
        + f"const CONFIG = {json.dumps(cfg_time)};\n\n"
        + time_core
        + "\nreturn $input.all().map((item) => {\n"
        + "  const d = item.json;\n"
        + "  const first = toMin(d.match_time);\n"
        + "  const lineFit = {};\n  const safe = [];\n  const risky = [];\n  const blocked = [];\n  const notes = [];\n"
        + "  for (let line = 1; line <= CONFIG.lines; line++) {\n"
        + "    const r = timeFit(d.time_window || null, line, first, CONFIG);\n"
        + "    lineFit[line] = r.status;\n"
        + "    (r.status === 'ok' ? safe : r.status === 'risky' ? risky : blocked).push(line);\n"
        + "    if (r.status !== 'ok') notes.push(`Line ${line} (${r.start}): ${r.why}`);\n"
        + "  }\n"
        + "  return { json: { ...d, line_fit: lineFit, safe_lines: safe, risky_lines: risky, blocked_lines: blocked, line_fit_notes: notes } };\n"
        + "});\n"
    )
    cases = [{k: v for k, v in c.items()} for c in lineup_cases(roster, cfg)]
    lineups_node = (
        BANNER
        + "// Node: Lineups to check. Test lineups for the Rules checker. The lineup planner will replace this later.\n"
        + "// Players: p01 Ava, p02 Brooke, p03 Carla, p04 Dana, p05 Ellie, p06 Fran, p08 Hana, p11 Kara, p12 Lena, p13 Maya, p15 Priya, p16 Sam.\n"
        + f"const CASES = {js_list(cases)};\n"
        + "return CASES.map((c) => ({ json: c }));\n"
    )
    # ---- planner nodes
    plan_roster = [{"id": p["id"], "name": p["name"], "side": p.get("side", "either")} for p in roster["players"]]
    cfg_plan = {k: cfg[k] for k in ("lines", "players_per_line", "pair_move_limit", "individual_move_limit", "line_duration_hours")}
    plan_core = (HERE / "src" / "planner_core.js").read_text(encoding="utf-8")
    pcases = planner_cases(roster)
    planner_node = (
        BANNER
        + "// Node: Lineup planner. Input items: { scenario, available: [ids], first_start: \"13:00\", windows?: {id: \"until 16:00\"},\n"
        + "// baseline?: lineup, ranking?: [ids strongest first], exclude?: [ids], reserve?: [ids], fixed?: {\"3\": [id, id]}, k?: 3 }.\n"
        + "// Output: up to k legal lineups (best first) with a reason for every line, or why none exists.\n"
        + f"const ROSTER = {{ players: {js_list(plan_roster)} }};\n"
        + f"const CONFIG = {json.dumps(cfg_plan)};\n"
        + f"const HISTORY = {{ matches: {js_list(hist_min['matches'])} }};\n\n"
        + rules_core + "\n" + time_core + "\n" + plan_core
        + "\nconst state = buildState(HISTORY);\n"
        + "return $input.all().map((item) => ({ json: { scenario: item.json.scenario, ...plan(ROSTER, CONFIG, state, item.json) } }));\n"
    )
    scenarios_node = (
        BANNER
        + "// Node: Planner scenarios. Demo requests for the Lineup planner. In real use these come from the captain and the recorded replies.\n"
        + f"const SCENARIOS = {js_list(pcases[:4])};\n"
        + "return SCENARIOS.map((s) => ({ json: s }));\n"
    )
    verify_node = (
        BANNER
        + "// Node: Options to check. Turns every planner option into an item for the Rules checker, as a second, independent check.\n"
        + "const out = [];\n"
        + "for (const item of $input.all()) {\n"
        + "  const r = item.json;\n"
        + "  for (const o of r.options) out.push({ json: { case: `${r.scenario} / option ${o.rank}`, lineup: o.lineup, available: r.pool } });\n"
        + "}\n"
        + "return out;\n"
    )
    # ---- setup flow nodes (JavaScript only; tested by tests/test_setup_import.py)
    alta = rc.load_json("alta_leagues.json")
    leagues_js = "const LEAGUES = {\n" + ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in alta["leagues"].items()) + "\n};\n"
    setup_header = leagues_js + f"const LEVELS = {json.dumps({'flights': alta['levels']['flights']})};\n\n"
    setup_core = (HERE / "src" / "setup_core.js").read_text(encoding="utf-8")
    emails_core = (HERE / "src" / "emails_core.js").read_text(encoding="utf-8")
    setup_checks_node = (
        BANNER
        + "// Node: Check the league, roster or schedule. Input item: { kind: 'league' | 'roster' | 'schedule', ...details }.\n"
        + "//   league:   { league, season, level_flight? }\n"
        + "//   roster:   { rows: [spreadsheet rows], league, roster_min }\n"
        + "//   schedule: { rows: [spreadsheet rows], league, year }\n"
        + "// Always returns { kind, ok, ... } plus the problems found (errors block, warnings do not).\n"
        + setup_header + setup_core
        + "\nconst item = $input.first().json;\n"
        + "let result;\n"
        + "if (item.kind === 'league') result = leagueCheck(item.league, item.season, item.level_flight);\n"
        + "else if (item.kind === 'roster') result = checkRoster(item.rows || [], item);\n"
        + "else if (item.kind === 'schedule') result = checkSchedule(item.rows || [], item);\n"
        + "else result = { ok: false, error: `Unknown check \"${item.kind}\".` };\n"
        + "const ok = result.ok !== undefined ? result.ok : result.summary.ok;\n"
        + "return [{ json: { kind: item.kind, team_id: item.team_id || null, ...result, ok } }];\n"
    )
    invite_node = (
        BANNER
        + "// Node: Write the invite email. Input item: { captain_name, captain_email, base_url }. Output: the invite (link, expiry, email text).\n"
        + "// Makes a private team_id for the link. Nothing is sent here.\n"
        + emails_core
        + "\nfunction randomId() {\n"
        + "  try { return require('crypto').randomBytes(18).toString('hex'); } catch (e) { /* not available here */ }\n"
        + "  try { return crypto.randomUUID().replace(/-/g, '') + crypto.randomUUID().replace(/-/g, '').slice(0, 4); } catch (e) { /* not available here */ }\n"
        + "  return Array.from({ length: 36 }, () => Math.floor(Math.random() * 16).toString(16)).join('');\n"
        + "}\n"
        + "const input = $input.first().json;\n"
        + "const invite = makeInvite({ ...input, form_path: 'tca-setup-2-league', team_id: input.team_id || randomId(), now_iso: input.now_iso || new Date().toISOString() });\n"
        + "return [{ json: invite }];\n"
    )
    intro_node = (
        BANNER
        + "// Node: Write the players' intro emails. Input item: { captain_name, league, season, players: [{ name, email }] }. One output item per player.\n"
        + "// Nothing is sent here.\n"
        + emails_core
        + "\nconst a = $input.first().json;\n"
        + "return makeIntroEmails(a).map((e) => ({ json: e }));\n"
    )
    entry_node = (
        BANNER
        + "// Node: Write the lineup entry sheet. Input item: { captain_name, captain_email, league, season, year, level_flight, week, date, home_away, opponent, facility, start_times, lineup: [[nameA, nameB] x lines], line_times?, comment?, reasons? }.\n"
        + "// Nothing is sent here, and nothing is ever sent to ALTA.\n"
        + emails_core
        + "\nconst a = $input.first().json;\n"
        + "return [{ json: { to: a.captain_email, ...makeEntrySheet(a) } }];\n"
    )
    cases_file = js({"lineups": cases, "planner_cases": pcases, "expected": expected(roster, cfg, hist)}) + "\n"
    return {
        "nodes/rules_checker.js": rules_node,
        "nodes/line_time_fit.js": time_node,
        "nodes/lineups_to_check.js": lineups_node,
        "nodes/lineup_planner.js": planner_node,
        "nodes/planner_scenarios.js": scenarios_node,
        "nodes/options_to_check.js": verify_node,
        "nodes/setup_checks.js": setup_checks_node,
        "nodes/invite_email.js": invite_node,
        "nodes/intro_emails.js": intro_node,
        "nodes/entry_sheet.js": entry_node,
        "checker_cases.json": cases_file,
    }


if __name__ == "__main__":
    (HERE / "nodes").mkdir(exist_ok=True)
    for name, text in build().items():
        (HERE / name).write_text(text, encoding="utf-8")
        print("wrote", f"n8n/{name}", len(text), "chars")
